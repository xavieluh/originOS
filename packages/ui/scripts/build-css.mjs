// Emits dist/tokens.css from the compiled tokens (run after tsc).
import { writeFileSync } from "node:fs";
import { colors, cssVar, fonts, motion, radii } from "../dist/tokens.js";

const block = (theme) =>
  Object.entries(colors[theme])
    .map(([name, value]) => `  ${cssVar(name)}: ${value};`)
    .join("\n");

const shared = [
  ...Object.entries(fonts).map(([k, v]) => `  --oo-font-${k}: ${v};`),
  ...Object.entries(radii).map(([k, v]) => `  --oo-radius-${k}: ${v};`),
  `  --oo-motion-fast: ${motion.fast};`,
  `  --oo-motion-base: ${motion.base};`,
  `  --oo-easing: ${motion.easing};`,
].join("\n");

const css = `/* Generated by packages/ui/scripts/build-css.mjs from src/tokens.ts. Do not edit. */
:root {
${shared}
  color-scheme: light;
${block("light")}
}
:root[data-theme="dark"] {
  color-scheme: dark;
${block("dark")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block("dark").replace(/^/gm, "  ")}
  }
}
`;
writeFileSync(new URL("../dist/tokens.css", import.meta.url), css);
